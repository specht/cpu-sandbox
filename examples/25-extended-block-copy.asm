; MiniCPU 8X: X points to source, Y points to the framebuffer destination.
; This colorful 16x8 mosaic is copied byte-for-byte, not drawn by graphics opcodes.
; 4 bits/pixel -> 2 pixels/byte -> 64 bytes total.
.display 0x0800, 16, 8, indexed4, sweetie_16

    LDX image                 ; source in ordinary shared RAM
    LDY 0x0800                ; display controller reads this RAM region
    LDI C, 64
copy:
    LDA A, [X]
    STA [Y], A
    INCX
    INCY
    DEC C
    JNZ copy
    HLT

